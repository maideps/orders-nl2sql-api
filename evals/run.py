"""Evaluate the question endpoint against a real LLM.

Usage: python -m evals.run [--report evals/REPORT.md]

Needs LLM_API_KEY in `.env` and the database built with `python -m app.load_orders`.
It sends real requests, so it costs money and is not part of `check.py`.

Each case in `evals/questions.json` is one of two kinds:

- A question with a `gold_sql`: a reference query written by hand. The case passes when
  the endpoint answers 200 and its rows hold the same values as the reference rows.
  What is compared is the result, not the SQL text, because many queries are correct.
- A question with `expect_refusal`: something the API must not do or cannot know. The
  case passes when the endpoint answers with an error and runs nothing.
"""

import argparse
import json
import math
import time
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from fastapi.testclient import TestClient

from app.config import DB_PATH
from app.db import run_query
from app.main import app, get_sql_generator

QUESTIONS_PATH = Path(__file__).parent / "questions.json"
REFUSAL_ERRORS = {"question_not_answerable", "invalid_query"}


@dataclass
class CaseResult:
    case_id: str
    question: str
    passed: bool
    outcome: str
    seconds: float
    sql: str | None


def load_cases() -> list[dict]:
    return json.loads(QUESTIONS_PATH.read_text(encoding="utf-8"))


def _same_value(expected, actual) -> bool:
    if isinstance(expected, (int, float)) and isinstance(actual, (int, float)):
        return math.isclose(expected, actual, abs_tol=0.01)
    return expected == actual


def _row_contains(actual_row: list, expected_row: list) -> bool:
    """True when every expected value appears in the actual row, each used once."""
    remaining = list(actual_row)
    for expected in expected_row:
        match = next((v for v in remaining if _same_value(expected, v)), None)
        if match is None:
            return False
        remaining.remove(match)
    return True


def rows_match(expected: list[list], actual: list[list], ordered: bool = False) -> bool:
    """Compare two results by value.

    The actual rows may carry extra columns (for example the country next to a total)
    and the columns may be in any order. The number of rows must be the same. Row order
    matters only when `ordered` is set, for questions that ask for a ranking.
    """
    if len(expected) != len(actual):
        return False
    if ordered:
        return all(_row_contains(a, e) for e, a in zip(expected, actual, strict=True))
    unused = list(actual)
    for expected_row in expected:
        match = next((a for a in unused if _row_contains(a, expected_row)), None)
        if match is None:
            return False
        unused.remove(match)
    return True


def evaluate_case(case: dict, client: TestClient, db_path: Path) -> CaseResult:
    start = time.monotonic()
    response = client.post("/ask", json={"question": case["question"]})
    seconds = time.monotonic() - start
    body = response.json()
    sql = body.get("sql")

    if case.get("expect_refusal"):
        refused = response.status_code == 422 and body.get("error") in REFUSAL_ERRORS
        outcome = body.get("error") if response.status_code != 200 else "answered (should refuse)"
        return CaseResult(case["id"], case["question"], refused, outcome, seconds, sql)

    if response.status_code != 200:
        outcome = f"{response.status_code} {body.get('error')}"
        return CaseResult(case["id"], case["question"], False, outcome, seconds, sql)

    _, expected_rows = run_query(case["gold_sql"], db_path)
    passed = rows_match(expected_rows, body["rows"], ordered=case.get("ordered", False))
    outcome = "correct" if passed else f"wrong result: {body['rows'][:3]}"
    return CaseResult(case["id"], case["question"], passed, outcome, seconds, sql)


def build_report(results: list[CaseResult], model: str) -> str:
    passed = sum(result.passed for result in results)
    answerable = [r for r, c in zip(results, load_cases(), strict=True) if "gold_sql" in c]
    refusals = [r for r, c in zip(results, load_cases(), strict=True) if c.get("expect_refusal")]
    seconds = sorted(result.seconds for result in results)

    lines = [
        "# Evaluation report",
        "",
        f"Model: `{model}` · Date: {date.today().isoformat()} · Generated by `python -m evals.run`",
        "",
        f"- **Overall: {passed}/{len(results)} passed**",
        f"- Questions about the data: {sum(r.passed for r in answerable)}/{len(answerable)} "
        "returned the same result as the reference query",
        f"- Requests that must be refused: {sum(r.passed for r in refusals)}/{len(refusals)} "
        "refused without running anything",
        f"- Latency: median {seconds[len(seconds) // 2]:.1f}s, slowest {seconds[-1]:.1f}s",
        "",
        "| Case | Question | Result | Seconds | SQL written by the LLM |",
        "|------|----------|--------|---------|------------------------|",
    ]
    for result in results:
        mark = "PASS" if result.passed else "**FAIL**"
        sql = f"`{result.sql}`" if result.sql else "—"
        lines.append(
            f"| {result.case_id} | {result.question} | {mark}: {result.outcome} "
            f"| {result.seconds:.1f} | {sql.replace('|', chr(92) + '|')} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--report", type=Path, help="write a markdown report to this file")
    args = parser.parse_args()

    client = TestClient(app)
    results = []
    for case in load_cases():
        result = evaluate_case(case, client, DB_PATH)
        results.append(result)
        print(f"{'PASS' if result.passed else 'FAIL'}  {result.case_id:<28} {result.outcome}")

    passed = sum(result.passed for result in results)
    print(f"\n{passed}/{len(results)} passed")
    if args.report:
        args.report.write_text(
            build_report(results, get_sql_generator().model), encoding="utf-8", newline="\n"
        )
        print(f"Report written to {args.report}")


if __name__ == "__main__":
    main()
